# Regenerates THIRD_PARTY_LICENSES from the module cache, so license texts
# are copied verbatim from each dependency rather than retyped (LIC-6).
# Usage: scripts/gen-third-party.sh > THIRD_PARTY_LICENSES
set -eu
GO=${GO:-go}
here=$(dirname "$0")
cat <<'HDR'
Third-party software included in Transporter
=============================================

Transporter is licensed under the Mozilla Public License 2.0 (see LICENSE).
It includes the components below, each under its own license. This file is
generated by scripts/gen-third-party.sh; `make license-check` fails if it is
out of date.

HDR
printf '%s\n' '----------------------------------------------------------------------'
cat "$here/third-party-wordlist.txt"
for m in $($GO list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}@{{.Version}}{{end}}{{end}}' ./cmd/transporter | sort -u); do
	path=${m%@*}
	ver=${m#*@}
	dir=$($GO list -m -f '{{.Dir}}' "$path")
	lic=""
	for f in LICENSE LICENSE.txt LICENSE.md COPYING; do
		if [ -f "$dir/$f" ]; then lic="$dir/$f"; break; fi
	done
	[ -n "$lic" ] || { echo "no license file for $m" >&2; exit 1; }
	printf '\n%s\n' '----------------------------------------------------------------------'
	printf 'Module: %s\nVersion: %s\n\n' "$path" "$ver"
	cat "$lic"
	for f in NOTICE NOTICE.txt NOTICE.md; do
		if [ -f "$dir/$f" ]; then printf '\n--- NOTICE ---\n\n'; cat "$dir/$f"; fi
	done
done
